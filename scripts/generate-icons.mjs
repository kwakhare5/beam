import { readFileSync, writeFileSync } from 'node:fs';
import { join, resolve } from 'node:path';

const map = {
  music: 'music',
  files: 'files',
  timer: 'timer',
  calendar: 'calendar',
  sliders: 'sliders-horizontal',
  x: 'x',
  alert: 'triangle-alert',
  copy: 'copy',
  trash: 'trash-2',
  file: 'file',
  folder: 'folder',
  monitor: 'monitor',
  check: 'check',
  plus: 'plus',
  chevronLeft: 'chevron-left',
  chevronRight: 'chevron-right'
};

const iconDir = resolve('node_modules/lucide-static/icons');
const pkg = JSON.parse(readFileSync('node_modules/lucide-static/package.json', 'utf8'));
const icons = {};

for (const [key, name] of Object.entries(map)) {
  const svg = readFileSync(join(iconDir, `${name}.svg`), 'utf8');
  const inner = svg
    .replace(/^[\s\S]*?<svg\b[^>]*>/, '')
    .replace(/<\/svg>\s*$/, '')
    .trim();

  if (!inner) {
    throw new Error(`Empty Lucide icon: ${name}`);
  }

  icons[key] = inner;
}

const output = `// Generated by scripts/generate-icons.mjs from lucide-static ${pkg.version}. Do not edit.\nexport const ICON_PATHS: Record<string, string> = ${JSON.stringify(icons, null, 2)};\n`;
writeFileSync('src/renderer/ui/icons.generated.ts', output);
console.log(`wrote ${Object.keys(icons).length} icons from lucide-static ${pkg.version}`);
